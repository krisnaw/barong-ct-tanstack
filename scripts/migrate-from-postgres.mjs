#!/usr/bin/env node
/**
 * ETL: Postgres (old barong-ct) → SQLite INSERT file for D1 (barong-ct-tanstack).
 *
 * Does NOT write to D1. It only generates:
 *   scripts/out/d1-import.sql  — apply with wrangler d1 execute
 *   scripts/out/id-map.json    — old serial id → new text id
 *
 * Usage:
 *   DATABASE_URL=postgresql://... node scripts/migrate-from-postgres.mjs
 *
 * Then (when you are ready):
 *   npx wrangler d1 execute barong-ct-v2 --local --file=scripts/out/d1-import.sql
 *   npx wrangler d1 execute barong-ct-v2 --remote --file=scripts/out/d1-import.sql
 *   npx wrangler d1 execute barong-ct-staging-v2 --remote --env staging --file=scripts/out/d1-import.sql
 *
 * Requires: npm install pg  (or: npm i -D pg)
 */

import { createHash, randomUUID } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import pg from 'pg'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT_DIR = join(__dirname, 'out')
const SQL_PATH = join(OUT_DIR, 'd1-import.sql')
const MAP_PATH = join(OUT_DIR, 'id-map.json')

const DATABASE_URL = process.env.DATABASE_URL
if (!DATABASE_URL) {
  console.error('Set DATABASE_URL to the old Postgres connection string.')
  process.exit(1)
}

/** Weekly club rides are homepage copy only — do not import as events. */
const WEEKLY_RIDE_NAME =
  /^(thursday\s+)?foreplay$|^(saturday\s+)?climax$|^(tuesday\s+)?quickie$/i

function isWeeklyRide(name) {
  return WEEKLY_RIDE_NAME.test(String(name ?? '').trim())
}

function toMs(value) {
  if (value == null) return null
  if (value instanceof Date) {
    const ms = value.getTime()
    return Number.isNaN(ms) ? null : ms
  }
  const ms = new Date(value).getTime()
  return Number.isNaN(ms) ? null : ms
}

function toIntMoney(value) {
  if (value == null || value === '') return 0
  const n = Number(value)
  if (Number.isNaN(n)) return 0
  return Math.round(n)
}

function sqlLiteral(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'boolean') return value ? '1' : '0'
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) return 'NULL'
    return String(Math.trunc(value) === value ? value : Math.round(value))
  }
  return `'${String(value).replaceAll("'", "''")}'`
}

function insert(table, row) {
  const cols = Object.keys(row)
  const vals = cols.map((c) => sqlLiteral(row[c]))
  return `INSERT INTO \`${table}\` (${cols.map((c) => `\`${c}\``).join(', ')}) VALUES (${vals.join(', ')});`
}

function slugify(name, id) {
  const base = String(name ?? 'event')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
  return `${base || 'event'}-${id}`
}

function formatEventDate(eventDate, startDate) {
  if (eventDate) {
    if (eventDate instanceof Date) {
      return eventDate.toISOString().slice(0, 10)
    }
    const s = String(eventDate)
    if (/^\d{4}-\d{2}-\d{2}/.test(s)) return s.slice(0, 10)
  }
  const ms = toMs(startDate)
  if (ms != null) return new Date(ms).toISOString().slice(0, 10)
  return '1970-01-01'
}

function formatEventTime(eventTime) {
  if (!eventTime) return '05:30'
  const s = String(eventTime)
  const m = s.match(/(\d{2}):(\d{2})/)
  if (m) return `${m[1]}:${m[2]}`
  return '05:30'
}

function mapTimeZone(tz) {
  if (!tz) return 'GMT+8'
  if (tz === 'Asia/Singapore' || tz === 'Asia/Jakarta') return 'GMT+8'
  return tz
}

function splitName(name) {
  const trimmed = String(name ?? '').trim()
  if (!trimmed) return { firstName: null, lastName: null }
  const [firstName, ...rest] = trimmed.split(/\s+/)
  return {
    firstName: firstName || null,
    lastName: rest.length ? rest.join(' ') : null,
  }
}

function mapId(map, oldId) {
  const key = String(oldId)
  if (!map[key]) map[key] = randomUUID()
  return map[key]
}

function inferKind(isGroupRide, maxCategoryPrice) {
  const paid = maxCategoryPrice > 0
  if (paid && isGroupRide) return 'flagship'
  if (paid) return 'paid'
  return 'free'
}

async function main() {
  const client = new pg.Client({ connectionString: DATABASE_URL })
  await client.connect()

  const lines = [
    '-- Generated by scripts/migrate-from-postgres.mjs',
    '-- Do not apply to production without review.',
    'PRAGMA foreign_keys = OFF;',
    '',
  ]

  const idMap = {
    event: {},
    event_category: {},
    event_group: {},
    event_promo: {},
    event_participant: {},
    event_payment: {},
    event_checkpoint: {},
    checkpoint_checkin: {},
  }

  const skippedEvents = []

  try {
    // --- users (keep text id) ---
    const { rows: users } = await client.query(`
      SELECT id, name, email, email_verified, image, created_at, updated_at,
             role, banned, ban_reason, ban_expires, verified_at
      FROM "user"
      ORDER BY created_at
    `)

    for (const u of users) {
      lines.push(
        insert('user', {
          id: u.id,
          name: u.name,
          email: u.email,
          email_verified: Boolean(u.email_verified),
          image: u.image,
          created_at: toMs(u.created_at) ?? Date.now(),
          updated_at: toMs(u.updated_at) ?? Date.now(),
          role: u.role,
          banned: u.banned == null ? false : Boolean(u.banned),
          ban_reason: u.ban_reason,
          ban_expires: toMs(u.ban_expires),
        }),
      )
    }
    lines.push('')

    // --- user_profile from user_detail + user.verified_at ---
    const { rows: details } = await client.query(`
      SELECT user_id, phone_number, identity_number, nationality, gender, blood_type,
             date_of_birth, emergency_contact_name, emergency_contact_number,
             province, city, postal_code, address
      FROM user_detail
    `)
    const detailByUser = new Map(details.map((d) => [d.user_id, d]))

    for (const u of users) {
      const d = detailByUser.get(u.id)
      const names = splitName(u.name)
      const now = toMs(u.created_at) ?? Date.now()
      lines.push(
        insert('user_profile', {
          user_id: u.id,
          first_name: names.firstName,
          last_name: names.lastName,
          phone: d?.phone_number ?? null,
          gender: d?.gender ?? null,
          blood_type: d?.blood_type ?? null,
          date_of_birth: d?.date_of_birth
            ? String(d.date_of_birth).slice(0, 10)
            : null,
          nationality: d?.nationality ?? null,
          id_number: d?.identity_number ?? null,
          emergency_contact_name: d?.emergency_contact_name ?? null,
          emergency_contact_phone: d?.emergency_contact_number ?? null,
          jersey_size: 'M',
          address: d?.address ?? null,
          apartment: null,
          city: d?.city ?? null,
          province: d?.province ?? 'Bali',
          postal: d?.postal_code ?? null,
          verified_at: toMs(u.verified_at),
          created_at: now,
          updated_at: toMs(u.updated_at) ?? now,
        }),
      )
    }
    lines.push('')

    // --- events (skip weekly rides) ---
    const { rows: events } = await client.query(`
      SELECT id, name, description, feature_image, start_date,
             "eventDate", "eventTime",
             time_zone, is_group_ride, has_jersey, registration_closes_at, status,
             location_name, location_address, regulation, created_at, updated_at
      FROM event
      ORDER BY id
    `)

    const { rows: categories } = await client.query(`
      SELECT id, name, description, event_id, price, currency, service_fee,
             max_participants, gpx_route, created_at, updated_at
      FROM event_category
      ORDER BY id
    `)

    const categoriesByEvent = new Map()
    for (const c of categories) {
      const list = categoriesByEvent.get(c.event_id) ?? []
      list.push(c)
      categoriesByEvent.set(c.event_id, list)
    }

    const importedEventIds = new Set()
    const usedSlugs = new Set()

    for (const e of events) {
      if (isWeeklyRide(e.name)) {
        skippedEvents.push({ id: e.id, name: e.name, reason: 'weekly_ride' })
        continue
      }

      const cats = categoriesByEvent.get(e.id) ?? []
      const maxPrice = Math.max(0, ...cats.map((c) => toIntMoney(c.price)))
      const kind = inferKind(Boolean(e.is_group_ride), maxPrice)
      const newId = mapId(idMap.event, e.id)
      importedEventIds.add(e.id)

      let slug = slugify(e.name, e.id)
      if (usedSlugs.has(slug)) {
        slug = `${slug}-${createHash('sha1').update(newId).digest('hex').slice(0, 6)}`
      }
      usedSlugs.add(slug)

      const closes = toMs(e.registration_closes_at)
      lines.push(
        insert('event', {
          id: newId,
          slug,
          name: e.name,
          description: e.description ?? '',
          regulation: e.regulation,
          feature_image: e.feature_image,
          feature_image_alt: null,
          kind,
          status: e.status ?? 'draft',
          event_date: formatEventDate(e.eventDate, e.start_date),
          event_time: formatEventTime(e.eventTime),
          time_zone: mapTimeZone(e.time_zone),
          location_name: e.location_name || 'TBD',
          location_address: e.location_address,
          registration_closes_at: closes
            ? new Date(closes).toISOString()
            : null,
          has_jersey: Boolean(e.has_jersey),
          is_group_ride: Boolean(e.is_group_ride),
          group_capacity: null,
          created_at: toMs(e.created_at) ?? Date.now(),
          updated_at: toMs(e.updated_at) ?? Date.now(),
        }),
      )
    }
    lines.push('')

    // --- categories ---
    const categoriesSorted = [...categories].sort((a, b) => a.id - b.id)
    const sortByEvent = new Map()
    for (const c of categoriesSorted) {
      if (!importedEventIds.has(c.event_id)) continue
      const order = sortByEvent.get(c.event_id) ?? 0
      sortByEvent.set(c.event_id, order + 1)
      const newId = mapId(idMap.event_category, c.id)
      lines.push(
        insert('event_category', {
          id: newId,
          event_id: idMap.event[String(c.event_id)],
          name: c.name,
          description: c.description,
          distance: null,
          price: toIntMoney(c.price),
          service_fee: toIntMoney(c.service_fee),
          currency: c.currency || 'IDR',
          max_participants: c.max_participants,
          gpx_route: c.gpx_route,
          sort_order: order,
          created_at: toMs(c.created_at) ?? Date.now(),
          updated_at: toMs(c.updated_at) ?? Date.now(),
        }),
      )
    }
    lines.push('')

    // --- groups ---
    // D1 enforces unique (event_id, name); old Postgres did not.
    const { rows: groups } = await client.query(`
      SELECT id, name, event_id, event_category_id FROM event_group ORDER BY id
    `)
    const nowMs = Date.now()
    const groupNamesByEvent = new Map()
    for (const g of groups) {
      if (!importedEventIds.has(g.event_id)) continue
      const newId = mapId(idMap.event_group, g.id)
      const categoryId =
        g.event_category_id != null &&
        idMap.event_category[String(g.event_category_id)]
          ? idMap.event_category[String(g.event_category_id)]
          : null
      let name = String(g.name ?? '').trim() || `Group ${g.id}`
      const used = groupNamesByEvent.get(g.event_id) ?? new Set()
      if (used.has(name)) {
        name = `${name} (${g.id})`
      }
      used.add(name)
      groupNamesByEvent.set(g.event_id, used)
      lines.push(
        insert('event_group', {
          id: newId,
          event_id: idMap.event[String(g.event_id)],
          event_category_id: categoryId,
          name,
          created_at: nowMs,
          updated_at: nowMs,
        }),
      )
    }
    lines.push('')

    // --- promos ---
    const { rows: promos } = await client.query(`
      SELECT id, event_id, promo, discount_value, discount_type, currency,
             usage_limit, used_count, starts_at, ends_at, is_active,
             created_at, updated_at
      FROM event_promo
      ORDER BY id
    `)
    for (const p of promos) {
      if (!importedEventIds.has(p.event_id)) continue
      const newId = mapId(idMap.event_promo, p.id)
      lines.push(
        insert('event_promo', {
          id: newId,
          event_id: idMap.event[String(p.event_id)],
          promo: p.promo,
          discount_value: toIntMoney(p.discount_value),
          discount_type:
            p.discount_type === 'percentage' || p.discount_type === 'percent'
              ? 'percent'
              : p.discount_type || 'fixed',
          currency: p.currency || 'IDR',
          usage_limit: p.usage_limit,
          used_count: p.used_count ?? 0,
          starts_at: toMs(p.starts_at),
          ends_at: toMs(p.ends_at),
          is_active: p.is_active == null ? true : Boolean(p.is_active),
          created_at: toMs(p.created_at) ?? nowMs,
          updated_at: toMs(p.updated_at) ?? nowMs,
        }),
      )
    }
    lines.push('')

    // --- participants ---
    const { rows: participants } = await client.query(`
      SELECT id, user_id, event_id, bib_id, status, event_category_id, event_group_id,
             price, service_fee, currency, promo_id, promo_code, discount_amount,
             final_price, jersey_size, kit_collected_at, created_at, updated_at
      FROM event_participant
      ORDER BY id
    `)
    const importedParticipantIds = new Set()
    for (const p of participants) {
      if (!importedEventIds.has(p.event_id)) continue
      const newId = mapId(idMap.event_participant, p.id)
      importedParticipantIds.add(p.id)
      lines.push(
        insert('event_participant', {
          id: newId,
          user_id: p.user_id,
          event_id: idMap.event[String(p.event_id)],
          event_category_id:
            p.event_category_id != null
              ? idMap.event_category[String(p.event_category_id)] ?? null
              : null,
          event_group_id:
            p.event_group_id != null
              ? idMap.event_group[String(p.event_group_id)] ?? null
              : null,
          status: p.status || 'draft',
          bib_number: p.bib_id,
          jersey_size: p.jersey_size,
          price: toIntMoney(p.price),
          service_fee: toIntMoney(p.service_fee),
          currency: p.currency || 'IDR',
          promo_id:
            p.promo_id != null
              ? idMap.event_promo[String(p.promo_id)] ?? null
              : null,
          promo_code: p.promo_code,
          discount_amount: toIntMoney(p.discount_amount),
          final_price: toIntMoney(p.final_price),
          kit_collected_at: toMs(p.kit_collected_at),
          created_at: toMs(p.created_at) ?? nowMs,
          updated_at: toMs(p.updated_at) ?? nowMs,
        }),
      )
    }
    lines.push('')

    // --- payments from event_payment ---
    const { rows: payments } = await client.query(`
      SELECT id, status, event_participant, invoice_number, expires_at, price,
             currency, payment_url, created_at, updated_at
      FROM event_payment
      ORDER BY id
    `)
    for (const pay of payments) {
      if (!importedParticipantIds.has(pay.event_participant)) continue
      const newId = mapId(idMap.event_payment, pay.id)
      const status = pay.status || 'pending'
      const created = toMs(pay.created_at) ?? nowMs
      const updated = toMs(pay.updated_at) ?? created
      const txn =
        pay.invoice_number ||
        `legacy-${pay.id}-${createHash('sha1').update(String(pay.id)).digest('hex').slice(0, 8)}`
      lines.push(
        insert('payment', {
          id: newId,
          order_id: null,
          participant_id: idMap.event_participant[String(pay.event_participant)],
          provider: 'doku',
          transaction_id: txn,
          status,
          method: null,
          amount: toIntMoney(pay.price),
          currency: pay.currency || 'IDR',
          checkout_url: pay.payment_url,
          paid_at: status === 'paid' ? updated : null,
          expires_at: toMs(pay.expires_at),
          created_at: created,
          updated_at: updated,
        }),
      )
    }
    lines.push('')

    // --- checkpoints ---
    const { rows: checkpoints } = await client.query(`
      SELECT id, event_id, name, sort_order, created_at, updated_at
      FROM event_checkpoint
      ORDER BY id
    `)
    for (const cp of checkpoints) {
      if (!importedEventIds.has(cp.event_id)) continue
      const newId = mapId(idMap.event_checkpoint, cp.id)
      lines.push(
        insert('event_checkpoint', {
          id: newId,
          event_id: idMap.event[String(cp.event_id)],
          name: cp.name,
          sort_order: cp.sort_order ?? 1,
          created_at: toMs(cp.created_at) ?? nowMs,
          updated_at: toMs(cp.updated_at) ?? nowMs,
        }),
      )
    }
    lines.push('')

    const { rows: checkpointCats } = await client.query(`
      SELECT checkpoint_id, category_id FROM checkpoint_category
    `)
    for (const link of checkpointCats) {
      const checkpointId = idMap.event_checkpoint[String(link.checkpoint_id)]
      const categoryId = idMap.event_category[String(link.category_id)]
      if (!checkpointId || !categoryId) continue
      lines.push(
        insert('checkpoint_category', {
          checkpoint_id: checkpointId,
          category_id: categoryId,
        }),
      )
    }
    lines.push('')

    const { rows: checkins } = await client.query(`
      SELECT id, checkpoint_id, participant_id, checked_in_at, checked_in_by
      FROM checkpoint_checkin
      ORDER BY id
    `)
    for (const row of checkins) {
      const checkpointId = idMap.event_checkpoint[String(row.checkpoint_id)]
      const participantId = idMap.event_participant[String(row.participant_id)]
      if (!checkpointId || !participantId) continue
      const newId = mapId(idMap.checkpoint_checkin, row.id)
      lines.push(
        insert('checkpoint_checkin', {
          id: newId,
          checkpoint_id: checkpointId,
          participant_id: participantId,
          checked_in_at: toMs(row.checked_in_at) ?? nowMs,
          checked_in_by: row.checked_in_by,
        }),
      )
    }

    lines.push('')
    lines.push('PRAGMA foreign_keys = ON;')
  } finally {
    await client.end()
  }

  mkdirSync(OUT_DIR, { recursive: true })
  writeFileSync(SQL_PATH, lines.join('\n') + '\n', 'utf8')
  writeFileSync(
    MAP_PATH,
    JSON.stringify({ skippedEvents, idMap }, null, 2) + '\n',
    'utf8',
  )

  console.log(`Wrote ${SQL_PATH}`)
  console.log(`Wrote ${MAP_PATH}`)
  console.log(
    `Users: imported. Events skipped (weekly): ${skippedEvents.length}`,
  )
  if (skippedEvents.length) {
    for (const s of skippedEvents) {
      console.log(`  - [${s.id}] ${s.name}`)
    }
  }
  console.log('')
  console.log('Next (when ready — not run by this script):')
  console.log(
    '  npx wrangler d1 execute barong-ct-v2 --local --file=scripts/out/d1-import.sql',
  )
  console.log(
    '  npx wrangler d1 execute barong-ct-v2 --remote --file=scripts/out/d1-import.sql',
  )
  console.log(
    '  npx wrangler d1 execute barong-ct-staging-v2 --remote --env staging --file=scripts/out/d1-import.sql',
  )
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
